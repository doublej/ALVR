//! Tunable mirror of `alvr_gui_common::theme`.
//!
//! `Default` equals the live ALVR theme, so the playground opens looking exactly
//! like the dashboard. `apply` is a value-driven copy of `theme::set_theme`, and
//! `export_rust` emits paste-ready code for `alvr/gui_common/src/theme.rs`.

use alvr_gui_common::theme;
use egui::{Color32, Context, CornerRadius, Margin, Stroke, TextStyle, ThemePreference, Vec2, Visuals};

#[derive(Clone)]
pub struct ThemeParams {
    pub accent: Color32,
    pub bg: Color32,
    pub lighter_bg: Color32,
    pub section_bg: Color32,
    pub darker_bg: Color32,
    pub separator_bg: Color32,
    pub fg: Color32,
    pub ok_green: Color32,
    pub ko_red: Color32,

    pub log_error: Color32,
    pub log_warning: Color32,
    pub log_info: Color32,
    pub log_debug: Color32,
    pub log_event: Color32,

    pub scrollbar_dot_diameter: f32,
    pub frame_padding: f32,
    pub corner_radius: u8,
    pub frame_text_spacing: f32,
    pub body_text_size: f32,
    pub slider_width: f32,
    pub interact_size: f32,
    pub item_spacing: Vec2,
    pub button_padding: Vec2,
    pub tooltip_delay: f32,
}

impl Default for ThemeParams {
    fn default() -> Self {
        use theme::log_colors as lc;
        Self {
            accent: theme::ACCENT,
            bg: theme::BG,
            lighter_bg: theme::LIGHTER_BG,
            section_bg: theme::SECTION_BG,
            darker_bg: theme::DARKER_BG,
            separator_bg: theme::SEPARATOR_BG,
            fg: theme::FG,
            ok_green: theme::OK_GREEN,
            ko_red: theme::KO_RED,
            log_error: lc::ERROR_LIGHT,
            log_warning: lc::WARNING_LIGHT,
            log_info: lc::INFO_LIGHT,
            log_debug: lc::DEBUG_LIGHT,
            log_event: lc::EVENT_LIGHT,
            scrollbar_dot_diameter: theme::SCROLLBAR_DOT_DIAMETER,
            frame_padding: theme::FRAME_PADDING,
            corner_radius: theme::CORNER_RADIUS,
            frame_text_spacing: theme::FRAME_TEXT_SPACING,
            body_text_size: 14.0,
            slider_width: 200.0,
            interact_size: 35.0,
            item_spacing: Vec2::new(15.0, 15.0),
            button_padding: Vec2::new(10.0, 10.0),
            tooltip_delay: 0.0,
        }
    }
}

impl ThemeParams {
    /// Value-driven copy of `theme::set_theme` — call once per frame so edits are live.
    pub fn apply(&self, ctx: &Context) {
        ctx.set_theme(ThemePreference::Dark);

        let mut style = (*ctx.style()).clone();
        style.spacing.slider_width = self.slider_width;
        style.spacing.interact_size.x = self.interact_size;
        style.spacing.interact_size.y = self.interact_size;
        style.spacing.item_spacing = self.item_spacing;
        style.spacing.button_padding = self.button_padding;
        style.spacing.window_margin = Margin::from(self.frame_padding);
        style.text_styles.get_mut(&TextStyle::Body).unwrap().size = self.body_text_size;
        style.interaction.tooltip_delay = self.tooltip_delay;
        ctx.set_style(style);

        let mut visuals = Visuals::dark();
        let radius = CornerRadius::same(self.corner_radius);

        visuals.widgets.active.bg_fill = self.accent;
        visuals.widgets.active.fg_stroke = Stroke::new(1.0_f32, self.fg);
        visuals.widgets.active.corner_radius = radius;
        visuals.widgets.inactive.fg_stroke = Stroke::new(1.0_f32, self.fg);
        visuals.widgets.inactive.corner_radius = radius;
        visuals.widgets.hovered.corner_radius = radius;
        visuals.widgets.open.bg_fill = self.separator_bg;
        visuals.widgets.open.corner_radius = radius;
        visuals.selection.bg_fill = self.accent;
        visuals.selection.stroke = Stroke::new(1.0_f32, self.fg);
        visuals.faint_bg_color = self.darker_bg;
        visuals.widgets.noninteractive.bg_fill = self.bg;
        visuals.widgets.noninteractive.fg_stroke = Stroke::new(1.0_f32, self.fg);
        visuals.widgets.noninteractive.bg_stroke = Stroke::new(0.5_f32, self.separator_bg);
        // Frame corner radius is intentionally larger than widget radius.
        visuals.widgets.noninteractive.corner_radius =
            CornerRadius::same(self.corner_radius.saturating_add(self.frame_padding as u8));

        ctx.set_visuals(visuals);
    }

    /// Emit `theme.rs`-shaped Rust for the tuned constants. Spacing changes live
    /// inside `set_theme`, so those are emitted as a comment block to splice in.
    pub fn export_rust(&self) -> String {
        let p = self;
        format!(
            "// Generated by alvr_theme_playground — paste into alvr/gui_common/src/theme.rs\n\
\n\
pub const ACCENT: Color32 = {accent};\n\
pub const BG: Color32 = {bg};\n\
pub const LIGHTER_BG: Color32 = {lighter_bg};\n\
pub const SECTION_BG: Color32 = {section_bg};\n\
pub const DARKER_BG: Color32 = {darker_bg};\n\
pub const SEPARATOR_BG: Color32 = {separator_bg};\n\
pub const FG: Color32 = {fg};\n\
pub const SCROLLBAR_DOT_DIAMETER: f32 = {sdd:?};\n\
pub const SWITCH_DOT_DIAMETER: f32 = SCROLLBAR_DOT_DIAMETER;\n\
pub const FRAME_PADDING: f32 = {fp:?};\n\
pub const CORNER_RADIUS: u8 = {cr};\n\
pub const FRAME_TEXT_SPACING: f32 = {fts:?};\n\
\n\
pub const OK_GREEN: Color32 = {ok};\n\
pub const KO_RED: Color32 = {ko};\n\
\n\
pub mod log_colors {{\n\
    use egui::epaint::Color32;\n\
\n\
    pub const ERROR_LIGHT: Color32 = {le};\n\
    pub const WARNING_LIGHT: Color32 = {lw};\n\
    pub const INFO_LIGHT: Color32 = {li};\n\
    pub const DEBUG_LIGHT: Color32 = {ld};\n\
    pub const EVENT_LIGHT: Color32 = {lev};\n\
}}\n\
\n\
// --- splice into set_theme() ---\n\
//   style.spacing.slider_width = {slw:?};\n\
//   style.spacing.interact_size.x = {is:?};\n\
//   style.spacing.interact_size.y = {is:?};\n\
//   style.spacing.item_spacing = egui::vec2({isx:?}, {isy:?});\n\
//   style.spacing.button_padding = egui::vec2({bpx:?}, {bpy:?});\n\
//   Body text size = {bts:?};\n\
//   style.interaction.tooltip_delay = {td:?};\n",
            accent = col(p.accent),
            bg = col(p.bg),
            lighter_bg = col(p.lighter_bg),
            section_bg = col(p.section_bg),
            darker_bg = col(p.darker_bg),
            separator_bg = col(p.separator_bg),
            fg = col(p.fg),
            sdd = p.scrollbar_dot_diameter,
            fp = p.frame_padding,
            cr = p.corner_radius,
            fts = p.frame_text_spacing,
            ok = col(p.ok_green),
            ko = col(p.ko_red),
            le = col(p.log_error),
            lw = col(p.log_warning),
            li = col(p.log_info),
            ld = col(p.log_debug),
            lev = col(p.log_event),
            slw = p.slider_width,
            is = p.interact_size,
            isx = p.item_spacing.x,
            isy = p.item_spacing.y,
            bpx = p.button_padding.x,
            bpy = p.button_padding.y,
            bts = p.body_text_size,
            td = p.tooltip_delay,
        )
    }
}

fn col(c: Color32) -> String {
    format!("Color32::from_rgb({}, {}, {})", c.r(), c.g(), c.b())
}
